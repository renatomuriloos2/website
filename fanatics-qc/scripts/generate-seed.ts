// Generates supabase/seed.sql from lib/domain/catalog.ts so the database
// protocol (test methods, decoration methods, requirements) always matches the
// app's defaults. Run: npx tsx scripts/generate-seed.ts
import { writeFileSync } from "fs";
import { join } from "path";
import { DECORATIONS, FIBERS, TEST_METHODS } from "../lib/domain/catalog";
import { specFor } from "../lib/domain/engine";

const q = (s: string | null | undefined) => (s === null || s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));

const out: string[] = [
  "-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.",
  "-- Default Fanatics QC protocol. Safe to re-run (upserts).",
  "",
];

out.push("insert into public.test_methods (id, code, standards, name_en, name_es, category, kind, is_base, is_critical) values");
out.push(
  TEST_METHODS.map((t) => `  (${q(t.id)}, ${q(t.code)}, ${q(t.standards)}, ${q(t.name.en)}, ${q(t.name.es)}, ${q(t.category)}, ${q(t.kind)}, ${Boolean(t.base)}, ${Boolean(t.critical)})`).join(",\n") +
    "\non conflict (id) do update set code = excluded.code, standards = excluded.standards, name_en = excluded.name_en, name_es = excluded.name_es, category = excluded.category, kind = excluded.kind, is_base = excluded.is_base, is_critical = excluded.is_critical;\n"
);

out.push("insert into public.decoration_methods (code, name_en, name_es, family, process_temp_c, low_temp_c, dwell_s) values");
out.push(
  DECORATIONS.map((d) => `  (${q(d.code)}, ${q(d.name.en)}, ${q(d.name.es)}, ${q(d.family)}, ${n(d.processTempC)}, ${n(d.lowTempC)}, ${n(d.dwellS)})`).join(",\n") +
    "\non conflict (code) do update set name_en = excluded.name_en, name_es = excluded.name_es, family = excluded.family, process_temp_c = excluded.process_temp_c, low_temp_c = excluded.low_temp_c, dwell_s = excluded.dwell_s;\n"
);

out.push("insert into public.decoration_method_tests (decoration_code, test_id, critical) values");
out.push(
  DECORATIONS.flatMap((d) => d.tests.map((t) => `  (${q(d.code)}, ${q(t.testId)}, ${t.critical})`)).join(",\n") +
    "\non conflict (decoration_code, test_id) do update set critical = excluded.critical;\n"
);

const reqRows: string[] = [];
for (const f of FIBERS) {
  for (const t of TEST_METHODS) {
    for (const r of t.readings) {
      const s = specFor(t, f.code, r.key);
      reqRows.push(`  (${q(f.code)}, ${q(t.id)}, ${q(r.key)}, ${n(s.min)}, ${n(s.max)}, ${s.abs})`);
    }
  }
}
out.push("insert into public.requirements (fiber, test_id, reading_key, min_value, max_value, use_abs) values");
out.push(reqRows.join(",\n") + "\non conflict (fiber, test_id, reading_key) do nothing;\n");

writeFileSync(join(__dirname, "..", "supabase", "seed.sql"), out.join("\n"));
console.log(`seed.sql written: ${TEST_METHODS.length} tests, ${DECORATIONS.length} decorations, ${reqRows.length} requirement rows`);
